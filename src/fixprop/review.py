"""Human review: a local labelling page, and merging the human verdicts into the results.

  python -m fixprop review --reviewer <name> [--port 8765]
      starts a web page on this machine (listening on 127.0.0.1 only), one pair per page:
        The fix               the hunks of the bug fix in the original file, with 10 lines before and after
        The unfixed copy      the other driver's current code, with the lines that still have the pre-fix code marked
        Claude Code's verdict the verdict, summary and evidence from reading the code; can be hidden for blind review
      Each verdict is saved immediately to judgments/review/<name>.jsonl, one line per pair, replaced when changed.

The page content is generated by `python -m fixprop all` into benchmark/review_items.json, so reviewing needs only this
repository, not the data in data/.

How the verdicts are used (merge):
  For every reviewed pair, the reviewers' common verdict is the final verdict; when reviewers disagree it is conflict.
  The final benchmark holds only reviewed pairs, in benchmark/final.jsonl; the counts go to human_review in summary.json.
  Pairs nobody has reviewed are not part of the final benchmark.
"""

from __future__ import annotations

import json
import os
import re
import tempfile
import threading
from collections import Counter
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

from . import gitio, hunks, paths
from .candidates import blob_url, commit_url
from .census import out_dir, unit_level
from .codebases import ORDER, Codebase, all_repos, get
from .common import log, read_jsonl, write_jsonl

REVIEW_DIR = "review"  # judgments/review/<reviewer>.jsonl
VERDICTS = ("missing", "not_missing", "unsure")
REASONS = ("not_a_fix", "not_applicable", "fixed_differently", "other")
REVIEWER = re.compile(r"^[A-Za-z0-9_-]{1,32}$")
CONTEXT = 10  # lines of context around the fix's hunks
RADIUS = 10  # lines shown before and after the marked lines of the copy
FUNC_LINES = 40  # diverged pairs: how many lines of the copy's same-named function to show
MAX_FILES, MAX_HUNKS, MAX_LINES = 4, 6, 160

LABEL_TEXT = {
    "missing": "Flagged as a missed fix", "not_applicable": "Fix does not apply to the copy",
    "not_a_fix": "Not a bug fix", "fixed_differently": "Copy already handles it differently", "unsure": "Unsure",
    "same_bug": "Flagged as a missed fix (written differently, so the script did not match it)",
    "not_needed_hw": "Not needed: different chip, device or board",
    "not_needed_absent": "Not needed: the copy does not have this feature or code", "already_ok": "Copy is already fine",
}


def review_dir() -> Path:
    return paths.JUDGMENTS / REVIEW_DIR


# ------------------------------------------------------------------ page content


def _hunk(h: hunks.Hunk) -> dict:
    lines = [[t, s] for t, s in h.lines]
    if len(lines) > MAX_LINES:
        lines = lines[:MAX_LINES] + [["...", f"({len(h.lines) - MAX_LINES} more lines in this hunk, not shown)"]]
    return {"old_start": h.old_start, "new_start": h.new_start, "lines": lines}


def _old_len(h: hunks.Hunk) -> int:
    return sum(1 for t, _ in h.lines if t in (" ", "-"))


def _wide_hunks(gitdir: Path, old: str, new: str, starts: list[int]) -> list[dict]:
    """The hunks of the fix that contain these starting lines (of the 3-line-context diff), redone with CONTEXT lines of
    context."""
    small = hunks.parse_diff(gitio.diff_blobs(gitdir, old, new))
    wide = hunks.parse_diff(gitio.diff_blobs(gitdir, old, new, context=CONTEXT))
    out, used = [], set()
    for s in starts:
        k = next((i for i, h in enumerate(wide) if h.old_start <= s < h.old_start + max(1, _old_len(h))), None)
        if k is None:  # not found: use the hunk with 3 lines of context
            h = next((h for h in small if h.old_start == s), None)
            if h is not None:
                out.append(_hunk(h))
            continue
        if k not in used:
            used.add(k)
            out.append(_hunk(wide[k]))
    return out[:MAX_HUNKS]


def _blocks(lines: list[str], marks: list[int], radius: int) -> list[dict]:
    """The lines of a file around marks: [{start, lines}], adjacent ranges merged, at most 3 ranges."""
    out: list[dict] = []
    for n in sorted(set(marks)):
        lo, hi = max(1, n - radius), min(len(lines), n + radius)
        if out and lo <= out[-1]["end"] + 1:
            out[-1]["end"] = max(out[-1]["end"], hi)
        else:
            out.append({"start": lo, "end": hi})
    return [{"start": b["start"], "lines": lines[b["start"] - 1:b["end"]]} for b in out[:3]]


def _claude(r: dict, pins: dict[str, str]) -> dict:
    def url(repo: str, f: str, line: int) -> str:
        return blob_url(repo, pins[repo], f, [line]) if repo in pins else ""

    refs = [{"repo": x.get("repo") or r["target_repo"], "file": x.get("file", ""), "line": x.get("line"),
             "quote": x.get("quote", ""), "url": url(x.get("repo") or r["target_repo"], x.get("file", ""), x.get("line") or 0)}
            for x in r.get("evidence_refs") or []]
    c = {"label": r.get("label"), "label_text": LABEL_TEXT.get(r.get("label"), r.get("label")),
         "confidence": r.get("confidence"), "reader": r.get("reader"), "evidence": r.get("evidence"), "refs": refs}
    for k in ("title", "summary", "port", "impact", "impact_note", "same_problem_as", "same_problem_note"):
        if r.get(k):
            c[k] = r[k]
    if r.get("where"):
        w = r["where"]
        c["where"] = {"file": w["file"], "line": w["line"], "url": url(r["target_repo"], w["file"], w["line"])}
    return c


def _item(cb: Codebase, r: dict, a: dict, kind: str, pins: dict[str, str], msgs: dict) -> dict:
    gitdir = gitio.git_dir(r["repo"])
    if (r["repo"], r["commit"]) not in msgs:
        msgs[(r["repo"], r["commit"])] = gitio.text(gitdir, "log", "-1", "--format=%B", r["commit"]).strip()
    places = []
    if kind == "candidate":
        for row in [x for x in a["rows"] if x["status"] == "candidate"][:MAX_FILES]:
            sel = [h for h in row["hunks"] if h["status"] == "candidate" and (cb.count_delete_only or h["kind"] != "delete")]
            marks = sorted({n for h in sel for n in h["target_lines"]})
            tlines = (cb.root(row["target_repo"]) / row["target"]).read_text(encoding="utf-8", errors="replace").split("\n")
            places.append({
                "source": row["source"], "target": row["target"],
                "target_url": blob_url(row["target_repo"], row["target_commit"], row["target"], marks),
                "fix": _wide_hunks(gitdir, row["blobs"][0], row["blobs"][1], [h["old_start"] for h in sel]),
                "copy": _blocks(tlines, marks, RADIUS), "marks": marks,
            })
    else:  # diverged pairs: the files and hunks listed in the sample record, and where the copy's same-named function is
        rows = {(x["source"], x["target"]): x for x in a["rows"] if x["status"] == "diverged"}
        for f in r["files"]:
            row = rows[(f["source"], f["target"])]
            tlines = (cb.root(row["target_repo"]) / row["target"]).read_text(encoding="utf-8", errors="replace").split("\n")
            starts = [h["target_line"] for h in f["hunks"] if h["target_line"]]
            copy = [{"start": s, "lines": tlines[s - 1:s - 1 + FUNC_LINES]} for s in sorted(set(starts))[:2]]
            places.append({
                "source": f["source"], "target": f["target"], "target_url": f["target_url"],
                "fix": _wide_hunks(gitdir, row["blobs"][0], row["blobs"][1], [h["old_start"] for h in f["hunks"]]),
                "copy": copy, "marks": [],
                "functions": [h["function"] for h in f["hunks"] if h["function"]],
            })
    group = "claude_missing" if r.get("label") in ("missing", "same_bug") else ("other" if kind == "candidate" else "diverged")
    return {
        "id": r["id"], "codebase": cb.name, "kind": kind, "group": group,
        "fix": {"repo": r["repo"], "commit": r["commit"], "url": commit_url(r["repo"], r["commit"]), "date": r["date"],
                "subject": r["subject"], "message": msgs[(r["repo"], r["commit"])]},
        "copy": {"repo": r["target_repo"], "unit": r["target_unit"], "commit": pins[r["target_repo"]]},
        "still_fixed": a.get("still_fixed") if kind == "candidate" else None,
        "places": places, "claude": _claude(r, pins),
    }


def build_items() -> list[dict]:
    """All content of the review page. Uses only the results in benchmark/ and the repositories in data/repos/; the same
    inputs give the same content."""
    pins, msgs, items = all_repos(), {}, []
    for name in ORDER:
        cb = get(name)
        d = out_dir(cb)
        agg = unit_level(read_jsonl(d / "fix_status.jsonl"))
        for r in read_jsonl(d / "candidates.jsonl"):
            items.append(_item(cb, r, agg[(r["commit"], r["target_repo"], r["target_unit"])], "candidate", pins, msgs))
        for r in read_jsonl(d / "diverged_sample.jsonl"):
            items.append(_item(cb, r, agg[(r["commit"], r["target_repo"], r["target_unit"])], "diverged", pins, msgs))
    return sorted(items, key=_order)


def _order(it: dict) -> tuple:
    """Codebases in a fixed order; within a codebase, candidates first, then diverged pairs, each by ID number."""
    m = re.search(r"-D?(\d+)$", it["id"])
    return (ORDER.index(it["codebase"]), it["kind"] != "candidate", int(m.group(1)) if m else 0, it["id"])


def write_items() -> int:
    items = build_items()
    f = paths.OUT / "review_items.json"
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(json.dumps(items, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    log(f"[review] review page content: {len(items)} pairs, {f.stat().st_size // 1024} KB")
    return len(items)


# ------------------------------------------------------------------ human verdicts


def check_review(x: dict, ids: set[str]) -> list[str]:
    i = x.get("id")
    p = []
    if i not in ids:
        p.append(f"ID {i!r} is not in the review set")
    if x.get("verdict") not in VERDICTS:
        p.append(f"{i}: verdict {x.get('verdict')!r} is not one of {VERDICTS}")
    if x.get("verdict") == "not_missing" and x.get("reason") not in REASONS:
        p.append(f"{i}: a verdict of not a missed fix needs a reason")
    if x.get("verdict") != "not_missing" and x.get("reason"):
        p.append(f"{i}: only a verdict of not a missed fix takes a reason")
    return p


def load_reviews(ids: set[str]) -> tuple[dict[str, list[dict]], list[str]]:
    """judgments/review/*.jsonl: ID -> [the verdict of each reviewer]."""
    out: dict[str, list[dict]] = {}
    problems = []
    for f in sorted(review_dir().glob("*.jsonl")):
        who = f.stem
        seen = set()
        for x in read_jsonl(f):
            p = check_review(x, ids)
            if x.get("id") in seen:
                p.append(f"{x.get('id')}: the same reviewer wrote two lines")
            seen.add(x.get("id"))
            problems += [f"{paths.rel(f)}: {s}" for s in p]
            if not p:
                out.setdefault(x["id"], []).append({"reviewer": who, **{k: x.get(k) for k in
                                                                       ("verdict", "reason", "note", "saw_llm")}})
    return out, problems


def merge(found: list[dict]) -> tuple[dict, int]:
    """Merge the human verdicts: write benchmark/final.jsonl and return (summary, number of problems). found holds the
    pairs Claude Code flagged."""
    items = {}
    for name in ORDER:
        for r in read_jsonl(out_dir(name) / "candidates.jsonl"):
            items[r["id"]] = (name, "candidate", r)
        for r in read_jsonl(out_dir(name) / "diverged_sample.jsonl"):
            items[r["id"]] = (name, "diverged", r)
    reviews, problems = load_reviews(set(items))
    for p in problems:
        log(f"[review] {p}")
    final = []
    for i in sorted(reviews, key=lambda s: (ORDER.index(items[s][0]), s)):
        name, kind, r = items[i]
        vs = {x["verdict"] for x in reviews[i]}
        final.append({
            "id": i, "codebase": name, "kind": kind,
            "final": vs.pop() if len(vs) == 1 else "conflict",
            "reviews": sorted(reviews[i], key=lambda x: x["reviewer"]),
            "claude": {"label": r.get("label"), "reader": r.get("reader"), "same_problem_as": r.get("same_problem_as")},
            "fix": {"repo": r["repo"], "commit": r["commit"], "subject": r["subject"]},
            "copy": {"repo": r["target_repo"], "unit": r["target_unit"]},
        })
    write_jsonl(paths.OUT / "final.jsonl", final)
    claude_missing = {r["id"] for r in found}
    got = {x["id"]: x for x in final}
    fin = Counter(x["final"] for x in final)
    human_missing = [x for x in final if x["final"] == "missing"]
    summary = {
        "reviewers": sorted({x["reviewer"] for v in reviews.values() for x in v}),
        "reviewed": len(final),
        "final": {k: fin.get(k, 0) for k in (*VERDICTS, "conflict")},
        "final_missing_distinct": sum(1 for x in human_missing
                                      if not (x["claude"]["same_problem_as"]
                                              and got.get(x["claude"]["same_problem_as"], {}).get("final") == "missing")),
        "claude_missing": {
            "total": len(claude_missing),
            "reviewed": sum(1 for i in claude_missing if i in got),
            **{f"human_{k}": sum(1 for i in claude_missing if got.get(i, {}).get("final") == k) for k in (*VERDICTS, "conflict")},
        },
        "claude_other_reviewed": sum(1 for i in got if i not in claude_missing),
        "claude_other_human_missing": sum(1 for i, x in got.items() if i not in claude_missing and x["final"] == "missing"),
    }
    log(f"[review] human review: {len(final)} pairs reviewed by {len(summary['reviewers'])} reviewers; "
        f"{summary['claude_missing']['reviewed']} of the {summary['claude_missing']['total']} flagged pairs reviewed")
    return summary, len(problems)


# ------------------------------------------------------------------ the local web page


class _Store:
    """One reviewer's verdict file. One line per pair, replaced when changed. Written to a temporary file first, then
    swapped in."""

    def __init__(self, reviewer: str, ids: set[str]):
        self.file = review_dir() / f"{reviewer}.jsonl"
        self.ids, self.lock = ids, threading.Lock()
        self.rows = {x["id"]: x for x in read_jsonl(self.file)} if self.file.exists() else {}

    def save(self, x: dict) -> list[str]:
        with self.lock:
            if x.get("verdict") is None:  # cleared
                self.rows.pop(x.get("id"), None)
            else:
                rec = {"id": x.get("id"), "verdict": x.get("verdict"), "reason": x.get("reason") or None,
                       "note": str(x.get("note") or "")[:4000], "saw_llm": bool(x.get("saw_llm")),
                       "time": datetime.now(timezone.utc).isoformat(timespec="seconds")}
                p = check_review(rec, self.ids)
                if p:
                    return p
                self.rows[rec["id"]] = rec
            self.file.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=self.file.parent, prefix=".tmp-")
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                for i in sorted(self.rows):
                    fh.write(json.dumps(self.rows[i], ensure_ascii=False) + "\n")
            os.replace(tmp, self.file)
            return []


def serve(reviewer: str, port: int = 8765) -> int:
    if not REVIEWER.match(reviewer):
        log("A reviewer name may only use letters, digits, underscore and hyphen, at most 32 characters.")
        return 2
    items_file = paths.OUT / "review_items.json"
    if not items_file.is_file():
        log(f"{paths.rel(items_file)} does not exist. Run python -m fixprop all first.")
        return 2
    items_raw = items_file.read_bytes()
    ids = {x["id"] for x in json.loads(items_raw)}
    store = _Store(reviewer, ids)
    page = (Path(__file__).with_name("review.html")).read_bytes()

    class Handler(BaseHTTPRequestHandler):
        def _send(self, code: int, body: bytes, ctype: str) -> None:
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)

        def _json(self, obj, code: int = 200) -> None:
            self._send(code, json.dumps(obj, ensure_ascii=False).encode("utf-8"), "application/json; charset=utf-8")

        def do_GET(self) -> None:  # noqa: N802
            if self.path in ("/", "/index.html"):
                self._send(200, page, "text/html; charset=utf-8")
            elif self.path == "/data.js":  # all page content plus this reviewer's verdicts; loaded synchronously by the page
                with store.lock:
                    head = json.dumps({"reviewer": reviewer, "file": paths.rel(store.file),
                                       "reviews": list(store.rows.values())}, ensure_ascii=False)
                body = b"window.REVIEW_DATA=" + head[:-1].encode("utf-8") + b',"items":' + items_raw.rstrip() + b"};\n"
                self._send(200, body, "text/javascript; charset=utf-8")
            else:
                self._send(404, b"not found", "text/plain")

        def do_POST(self) -> None:  # noqa: N802
            if self.path != "/api/review":
                self._send(404, b"not found", "text/plain")
                return
            n = int(self.headers.get("Content-Length") or 0)
            if n <= 0 or n > 65536:
                self._json({"ok": False, "problems": ["request is empty or too large"]}, 400)
                return
            try:
                x = json.loads(self.rfile.read(n))
            except ValueError:
                self._json({"ok": False, "problems": ["not valid JSON"]}, 400)
                return
            problems = store.save(x if isinstance(x, dict) else {})
            self._json({"ok": not problems, "problems": problems}, 200 if not problems else 400)

        def log_message(self, *args) -> None:  # keep the terminal quiet
            pass

    httpd = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    log(f"Review page: http://127.0.0.1:{port}/")
    log(f"Reviewer {reviewer}; verdicts are saved to {paths.rel(store.file)} ({len(store.rows)} so far). Press Ctrl+C to stop.")
    log("After reviewing, run python -m fixprop all to merge the verdicts into the results.")
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        httpd.server_close()
    return 0
